const SUPPORTED_LANGUAGES = ["en", "ta", "hi"];
const LANGUAGE_STORAGE_KEY = "language";
const LANGUAGE_META = {
  en: { full: "English", short: "EN" },
  ta: { full: "தமிழ்", short: "த" },
  hi: { full: "हिन्दी", short: "हि" }
};

function getStoredLanguage() {
  try {
    const saved = localStorage.getItem(LANGUAGE_STORAGE_KEY);
    return SUPPORTED_LANGUAGES.indexOf(saved) !== -1 ? saved : "en";
  } catch (e) {
    return "en";
  }
}

function getTranslation(lang, key) {
  const selectedPack = translations[lang] || translations.en;
  const selectedValue = selectedPack[key];
  if (selectedValue !== undefined && selectedValue !== null) {
    return selectedValue;
  }
  const fallbackValue = translations.en[key];
  return fallbackValue !== undefined && fallbackValue !== null ? fallbackValue : "";
}

document.addEventListener("DOMContentLoaded", () => {
  const menuToggle = document.getElementById("menu-toggle");
  const navLinks = document.getElementById("nav-links");
  const navItems = document.querySelectorAll(".nav-link");
  const currentYear = document.getElementById("current-year");
  const typingText = document.getElementById("typing-text");
  const themeToggle = document.getElementById("theme-toggle");
  const htmlEl = document.documentElement;
  const metaThemeColor = document.querySelector('meta[name="theme-color"]');
  const metaDescription = document.querySelector('meta[name="description"]');
  const languageSelector = document.getElementById("language-selector");
  const languageToggle = document.getElementById("language-toggle");
  const languageMenu = document.getElementById("language-menu");
  const languageOptions = languageMenu
    ? Array.from(languageMenu.querySelectorAll(".language-option"))
    : [];

  let currentLanguage = getStoredLanguage();
  let languageMenuOpen = false;
  let typingTimer = null;
  let typingToken = 0;

  const stopTyping = () => {
    typingToken++;
    if (typingTimer) {
      window.clearTimeout(typingTimer);
      typingTimer = null;
    }
  };

  const startTyping = (lang) => {
    if (!typingText) return;

    stopTyping();

    const translatedPhrases = getTranslation(lang, "hero.typingPhrases");
    const phrases = Array.isArray(translatedPhrases) && translatedPhrases.length
      ? translatedPhrases
      : translations.en["hero.typingPhrases"];

    if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
      typingText.textContent = phrases[0];
      return;
    }

    const token = typingToken;
    let phraseIndex = 0;
    let characterIndex = 0;
    let deleting = false;

    typingText.textContent = "";

    const typeEffect = () => {
      if (token !== typingToken) return;

      const phrase = phrases[phraseIndex];

      if (deleting) {
        characterIndex--;
        typingText.textContent = phrase.slice(0, characterIndex);
        let delay = 40;

        if (characterIndex === 0) {
          deleting = false;
          phraseIndex = (phraseIndex + 1) % phrases.length;
          delay = 300;
        }

        typingTimer = window.setTimeout(typeEffect, delay);
      } else {
        typingText.textContent = phrase.slice(0, characterIndex + 1);
        characterIndex++;
        let delay = 70;

        if (characterIndex === phrase.length) {
          deleting = true;
          delay = 1400;
        }

        typingTimer = window.setTimeout(typeEffect, delay);
      }
    };

    typingTimer = window.setTimeout(typeEffect, 600);
  };

  const updateThemeToggleLabel = () => {
    if (!themeToggle) return;
    const theme = htmlEl.getAttribute("data-theme") || "dark";
    const key = theme === "light" ? "theme.switchToDark" : "theme.switchToLight";
    themeToggle.setAttribute("aria-label", getTranslation(currentLanguage, key));
  };

  const updateMenuToggleLabel = () => {
    if (!menuToggle || !navLinks) return;
    const isOpen = navLinks.classList.contains("open");
    const key = isOpen ? "menu.close" : "menu.open";
    menuToggle.setAttribute("aria-label", getTranslation(currentLanguage, key));
  };

  const updateLanguageUi = (lang) => {
    const meta = LANGUAGE_META[lang] || LANGUAGE_META.en;

    const fullName = document.querySelector(".language-full");
    const shortName = document.querySelector(".language-short");
    if (fullName) fullName.textContent = meta.full;
    if (shortName) shortName.textContent = meta.short;

    languageOptions.forEach((option) => {
      const isSelected = option.getAttribute("data-lang") === lang;
      option.setAttribute("aria-selected", String(isSelected));
      option.classList.toggle("is-selected", isSelected);
    });
  };

  const applyLanguage = (lang, options = {}) => {
    const nextLanguage = SUPPORTED_LANGUAGES.indexOf(lang) !== -1 ? lang : "en";
    const shouldPersist = options.persist !== false;

    currentLanguage = nextLanguage;
    htmlEl.setAttribute("lang", nextLanguage);

    document.querySelectorAll("[data-i18n]").forEach((element) => {
      const key = element.getAttribute("data-i18n");
      const value = getTranslation(nextLanguage, key);
      if (typeof value === "string") {
        element.textContent = value;
      }
    });

    document.querySelectorAll("[data-i18n-html]").forEach((element) => {
      const key = element.getAttribute("data-i18n-html");
      const value = getTranslation(nextLanguage, key);
      if (typeof value === "string") {
        element.innerHTML = value;
      }
    });

    document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
      const key = element.getAttribute("data-i18n-aria");
      const value = getTranslation(nextLanguage, key);
      if (typeof value === "string") {
        element.setAttribute("aria-label", value);
      }
    });

    document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
      const key = element.getAttribute("data-i18n-alt");
      const value = getTranslation(nextLanguage, key);
      if (typeof value === "string") {
        element.setAttribute("alt", value);
      }
    });

    document.title = getTranslation(nextLanguage, "page.title");
    if (metaDescription) {
      metaDescription.setAttribute("content", getTranslation(nextLanguage, "page.description"));
    }

    updateLanguageUi(nextLanguage);
    updateThemeToggleLabel();
    updateMenuToggleLabel();
    startTyping(nextLanguage);

    if (shouldPersist) {
      try {
        localStorage.setItem(LANGUAGE_STORAGE_KEY, nextLanguage);
      } catch (e) {}
    }

    htmlEl.classList.remove("lang-loading");
  };

  const applyTheme = (theme) => {
    htmlEl.setAttribute("data-theme", theme);
    updateThemeToggleLabel();
    if (metaThemeColor) {
      metaThemeColor.setAttribute("content", theme === "light" ? "#F8FAFC" : "#050510");
    }
    try {
      localStorage.setItem("theme", theme);
    } catch (e) {}
  };

  const setLanguageMenu = (open) => {
    if (!languageMenu || !languageToggle) return;

    languageMenuOpen = open;
    languageMenu.hidden = !open;
    languageToggle.setAttribute("aria-expanded", String(open));

    if (open) {
      const selectedOption =
        languageOptions.find((option) => option.getAttribute("aria-selected") === "true") ||
        languageOptions[0];
      if (selectedOption) {
        window.setTimeout(() => selectedOption.focus(), 0);
      }
    }
  };

  const selectLanguage = (lang) => {
    applyLanguage(lang);
    setLanguageMenu(false);
    if (languageToggle) {
      languageToggle.focus();
    }
  };

  const currentTheme = htmlEl.getAttribute("data-theme") || "dark";
  updateThemeToggleLabel();
  if (metaThemeColor) {
    metaThemeColor.setAttribute("content", currentTheme === "light" ? "#F8FAFC" : "#050510");
  }

  applyLanguage(currentLanguage, { persist: false });

  if (themeToggle) {
    themeToggle.addEventListener("click", () => {
      const current = htmlEl.getAttribute("data-theme") || "dark";
      applyTheme(current === "dark" ? "light" : "dark");
    });
  }

  if (languageToggle) {
    languageToggle.addEventListener("click", () => {
      setLanguageMenu(!languageMenuOpen);
    });

    languageToggle.addEventListener("keydown", (event) => {
      if (event.key === "ArrowDown" || event.key === "ArrowUp") {
        event.preventDefault();
        setLanguageMenu(true);
      } else if (event.key === "Escape") {
        setLanguageMenu(false);
      }
    });
  }

  languageOptions.forEach((option, index) => {
    option.addEventListener("click", () => {
      selectLanguage(option.getAttribute("data-lang"));
    });

    option.addEventListener("keydown", (event) => {
      const key = event.key;

      if (key === "Enter" || key === " ") {
        event.preventDefault();
        selectLanguage(option.getAttribute("data-lang"));
      } else if (key === "ArrowDown") {
        event.preventDefault();
        languageOptions[(index + 1) % languageOptions.length].focus();
      } else if (key === "ArrowUp") {
        event.preventDefault();
        languageOptions[(index - 1 + languageOptions.length) % languageOptions.length].focus();
      } else if (key === "Home") {
        event.preventDefault();
        languageOptions[0].focus();
      } else if (key === "End") {
        event.preventDefault();
        languageOptions[languageOptions.length - 1].focus();
      } else if (key === "Escape") {
        event.preventDefault();
        setLanguageMenu(false);
        if (languageToggle) {
          languageToggle.focus();
        }
      } else if (key === "Tab") {
        setLanguageMenu(false);
      }
    });
  });

  document.addEventListener("click", (event) => {
    if (
      languageMenuOpen &&
      languageSelector &&
      !languageSelector.contains(event.target)
    ) {
      setLanguageMenu(false);
    }
  });

  if (currentYear) {
    currentYear.textContent = new Date().getFullYear();
  }

  if (menuToggle && navLinks) {
    const navMore = navLinks.querySelector(".nav-more");

    const toggleMenu = () => {
      const isOpen = navLinks.classList.toggle("open");
      menuToggle.setAttribute("aria-expanded", String(isOpen));
      updateMenuToggleLabel();
    };

    menuToggle.addEventListener("click", toggleMenu);

    menuToggle.addEventListener("keydown", (event) => {
      if (event.key === "Enter" || event.key === " ") {
        event.preventDefault();
        toggleMenu();
      }
    });

    navItems.forEach((link) => {
      link.addEventListener("click", () => {
        navLinks.classList.remove("open");
        if (navMore) navMore.open = false;
        menuToggle.setAttribute("aria-expanded", "false");
        updateMenuToggleLabel();
      });
    });

    document.addEventListener("keydown", (event) => {
      if (event.key === "Escape") {
        navLinks.classList.remove("open");
        if (navMore) navMore.open = false;
        menuToggle.setAttribute("aria-expanded", "false");
        updateMenuToggleLabel();
      }
    });

    document.addEventListener("click", (event) => {
      if (navMore && navMore.open && !navMore.contains(event.target)) {
        navMore.open = false;
      }

      if (
        navLinks.classList.contains("open") &&
        !navLinks.contains(event.target) &&
        !menuToggle.contains(event.target)
      ) {
        navLinks.classList.remove("open");
        menuToggle.setAttribute("aria-expanded", "false");
        updateMenuToggleLabel();
      }
    });
  }

  const sections = document.querySelectorAll("main section[id]");

  if ("IntersectionObserver" in window && sections.length) {
    const observer = new IntersectionObserver(
      (entries) => {
        entries.forEach((entry) => {
          if (!entry.isIntersecting) return;

          navItems.forEach((link) => {
            link.classList.toggle(
              "active",
              link.getAttribute("href") === `#${entry.target.id}`
            );
          });
        });
      },
      {
        rootMargin: "-30% 0px -60% 0px",
        threshold: 0
      }
    );

    sections.forEach((section) => observer.observe(section));
  }
});
